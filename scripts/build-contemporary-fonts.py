"""Build the contemporary fonts without changing existing Regular subsets.
Usage: python scripts/build-contemporary-fonts.py /path/to/downloaded-fonts
Requires fonttools[woff] and brotli; provenance is in public/fonts/README.md.
"""
import argparse
import re
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

parser = argparse.ArgumentParser()
parser.add_argument("source", type=Path)
source = parser.parse_args().source
root = Path(__file__).resolve().parent.parent
out = root / "public/fonts"
css = ["/* Generated by scripts/build-contemporary-fonts.py. */"]

def write_font(font, points, filename):
    options = subset.Options()
    options.flavor = "woff2"
    options.recalc_timestamp = False
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=points)
    sub.subset(font)
    font.flavor = "woff2"
    font.save(out / filename)

def face(family, weight, style, filename, unicode_range=""):
    css.append('@font-face {\n  font-family: "' + family + '";\n  font-style: ' + style + ';\n  font-weight: ' + weight + ';\n  font-display: swap;\n  src: url("/fonts/' + filename + '") format("woff2");' + ('\n  unicode-range: ' + unicode_range + ';' if unicode_range else '') + '\n}')

# Reuse the exact disjoint core/block partition of the existing Regular face.
old_css = (root / "app/(site)/editorial-fonts.css").read_text()
for label, unicode_range in re.findall(r'zhujinju-song-([\w]+)\.woff2.*?unicode-range: ([^;]+)', old_css, re.S):
    points = set()
    for run in unicode_range.split(','):
        edges = run.strip().removeprefix('U+').split('-')
        points.update(range(int(edges[0], 16), int(edges[-1], 16) + 1))
    font = TTFont(source / "SourceHanSerifSC-Medium.otf", recalcTimestamp=False)
    for name in font['name'].names:
        if name.nameID in (1, 3, 4, 6, 16, 17):
            value = "Medium" if name.nameID == 17 else "ZhujinjuSong-Medium"
            name.string = value.encode(name.getEncoding())
    cff = font['CFF '].cff
    cff.fontNames = ['ZhujinjuSong-Medium']
    cff.topDictIndex[0].FullName = 'Zhujinju Song Medium'
    cff.topDictIndex[0].FamilyName = 'Zhujinju Song'
    filename = f"zhujinju-song-medium-{label}.woff2"
    write_font(font, points, filename)
    face("Zhujinju Song", "500", "normal", filename, unicode_range)

latin = set(range(0x20, 0x180)) | set(range(0x2010, 0x2028)) | set(range(0x2030, 0x203B))
for filename, family, weight, style in [
    ("InstrumentSerif-Regular", "Instrument Serif", "400", "normal"),
    ("InstrumentSerif-Italic", "Instrument Serif", "400", "italic"),
    ("InstrumentSans", "Instrument Sans", "400 600", "normal"),
    ("Anton-Regular", "Anton", "400", "normal"),
]:
    font = TTFont(source / (filename + ".ttf"), recalcTimestamp=False)
    if family == "Instrument Sans":
        font = instantiateVariableFont(font, {"wdth": 100, "wght": (400, 600)}, inplace=True)
    write_font(font, latin, filename + ".woff2")
    face(family, weight, style, filename + ".woff2")
for name in ("LICENSE-instrument-serif.txt", "LICENSE-instrument-sans.txt", "LICENSE-anton.txt"):
    (out / name).write_text("\n".join(line.rstrip() for line in (source / name).read_text().splitlines()) + "\n")
(root / "app/(site)/contemporary-fonts.css").write_text('\n'.join(css) + '\n')
print(f"Built {len(css)-1} font faces; core Medium {(out / 'zhujinju-song-medium-core.woff2').stat().st_size:,} bytes")
