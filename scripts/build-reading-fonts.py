"""Group existing Song glyphs by use, preserving the old blocks for future CMS text.

Usage: python scripts/build-reading-fonts.py /path/to/source-fonts
Requires fonttools[woff]. SourceHanSerifSC-{Regular,Medium}.otf must be version
2.003, matching the licensed source used by the existing site subsets.
"""
import argparse
import hashlib
import json
import re
from collections import Counter
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser()
parser.add_argument("source", type=Path)
args = parser.parse_args()


def points(value):
    result = set()
    for item in value.split(","):
        edges = item.strip().removeprefix("U+").split("-")
        result.update(range(int(edges[0], 16), int(edges[-1], 16) + 1))
    return result


def ranges(values):
    runs = []
    for cp in sorted(values):
        if runs and cp == runs[-1][1] + 1:
            runs[-1][1] = cp
        else:
            runs.append([cp, cp])
    return ",".join(f"U+{lo:X}" if lo == hi else f"U+{lo:X}-{hi:X}" for lo, hi in runs)


def strings(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for item in value.values():
            yield from strings(item)
    elif isinstance(value, list):
        for item in value:
            yield from strings(item)


def titles(value):
    if isinstance(value, dict):
        for key, item in value.items():
            if key == "title" and isinstance(item, dict):
                yield item.get("zh", "")
            yield from titles(item)
    elif isinstance(value, list):
        for item in value:
            yield from titles(item)


content = json.loads((root / "content/site-content.json").read_text())
corpus = "".join(strings(content))
title_points = set(map(ord, "".join(titles(content))))
# Short shared navigation/home labels must not fetch a full prose group.
title_points.update(map(ord, "导览其及工注络脉"))
# Include UI labels and editorial copy authored in code, but not generated CSS.
for directory in (root / "components", root / "app/(site)", root / "lib"):
    sources = set(directory.rglob("*.tsx"))
    if directory == root / "lib":
        sources.update(directory.glob("*.ts"))
        sources.update((directory / "data").glob("*.ts"))
    for source in sorted(sources):
        code = source.read_text()
        corpus += code
        # Short UI titles authored as bt() literals belong in the shared core,
        # too: a contact heading should not pull in a whole prose group.
        for title in re.findall(r'\btitle:\s*bt\(\s*"([^"]*)"', code):
            title_points.update(map(ord, title))
frequency = Counter(ord(char) for char in corpus)
output = ["/* Generated by scripts/build-reading-fonts.py. Same glyphs; disjoint, demand-loaded groups. */"]
manifest = {"core": {}, "groups": []}
page_manifest = {}

for weight, style, css_file in [(400, "Regular", "editorial-fonts.css"), (500, "Medium", "contemporary-fonts.css")]:
    source_font = args.source / f"SourceHanSerifSC-{style}.otf"
    original = TTFont(source_font)
    assert original["name"].getDebugName(5).startswith("Version 2.003"), "Font version differs from existing subsets"
    css = (root / "app/(site)" / css_file).read_text()
    faces = re.findall(r"@font-face\s*\{[^}]+\}", css)
    chinese_faces = [face for face in faces if 'font-family: "Zhujinju Song"' in face]
    available = set().union(*(points(re.search(r"unicode-range: ([^;]+)", face)[1]) for face in chinese_faces))
    old_core = points(re.search(r"unicode-range: ([^;]+)", chinese_faces[0])[1])
    core = (old_core | title_points) & available
    used = (set(frequency) & available) - core
    ranked = sorted(used, key=lambda cp: (-frequency[cp], cp))
    groups = [("core", core)] + [(f"text-{start // 800:02d}", set(ranked[start:start + 800])) for start in range(0, len(ranked), 800)]
    covered = set()
    for label, glyphs in groups:
        assert not covered.intersection(glyphs)
        covered.update(glyphs)
        font = TTFont(source_font, recalcTimestamp=False)
        options = subset.Options()
        options.flavor = "woff2"
        options.recalc_timestamp = False
        sub = subset.Subsetter(options=options)
        sub.populate(unicodes=glyphs)
        sub.subset(font)
        for name in font["name"].names:
            if name.nameID in (1, 3, 4, 6, 16, 17):
                name.string = (style if name.nameID == 17 else f"ZhujinjuSong-{style}").encode(name.getEncoding())
        cff = font["CFF "].cff
        cff.fontNames = [f"ZhujinjuSong-{style}"]
        cff.topDictIndex[0].FullName = f"Zhujinju Song {style}"
        cff.topDictIndex[0].FamilyName = "Zhujinju Song"
        font.flavor = "woff2"
        temporary = root / "public/fonts" / f".reading-{weight}-{label}.woff2"
        font.save(temporary)
        digest = hashlib.sha256(temporary.read_bytes()).hexdigest()[:12]
        filename = f"reading-song-{weight}-{label}-{digest}.woff2"
        target = temporary.with_name(filename)
        temporary.replace(target)
        assert set(TTFont(target).getBestCmap()) == glyphs
        output.append(f'@font-face {{\n  font-family: "Zhujinju Song";\n  font-style: normal;\n  font-weight: {weight};\n  font-display: swap;\n  src: url("/fonts/{filename}") format("woff2");\n  unicode-range: {ranges(glyphs)};\n}}')
        manifest["groups"].append({"weight": weight, "name": label, "file": filename, "glyphs": len(glyphs), "bytes": target.stat().st_size})
        if label == "core":
            manifest["core"][str(weight)] = filename
        print(weight, label, len(glyphs), target.stat().st_size, flush=True)
    # Existing assets remain intact. Only their advertised ranges exclude the
    # new groups, so future CMS characters retain exactly the original coverage.
    for face in chinese_faces:
        remaining = points(re.search(r"unicode-range: ([^;]+)", face)[1]) - covered
        if remaining:
            output.append(re.sub(r"unicode-range: [^;]+", "unicode-range: " + ranges(remaining), face))
            assert not covered.intersection(remaining)
            covered.update(remaining)
    assert covered == available
    output.extend(face for face in faces if face not in chinese_faces)

    if weight == 400:
        # Start each reading page with only its own non-core characters. The
        # original complete family remains the fallback for later CMS changes.
        routes = {}
        for section, prefix in [("artworks", "collection"), ("exhibitions", "exhibitions"), ("articles", "journal")]:
            for record in content.get(section, []):
                if record.get("publicationStatus") == "draft":
                    continue
                routes[f"/{prefix}/{record['slug']}"] = "".join(strings(record))
        current = next((record for record in content.get("exhibitions", []) if record.get("slug") == "himalayan-art-2026"), None)
        if current:
            routes["/exhibitions"] = "".join(strings(current))
        routes["/about"] = "".join((root / name).read_text() for name in ["lib/site-config.ts", "lib/data/page-copy.ts", "lib/data/brand.ts"])
        for route, text in routes.items():
            glyphs = (set(map(ord, text)) & available) - core
            if not glyphs:
                continue
            font = TTFont(source_font, recalcTimestamp=False)
            options = subset.Options()
            options.flavor = "woff2"
            options.recalc_timestamp = False
            sub = subset.Subsetter(options=options)
            sub.populate(unicodes=glyphs)
            sub.subset(font)
            for name in font["name"].names:
                if name.nameID in (1, 3, 4, 6, 16, 17):
                    name.string = (style if name.nameID == 17 else f"ZhujinjuSong-{style}").encode(name.getEncoding())
            cff = font["CFF "].cff
            cff.fontNames = [f"ZhujinjuSong-{style}"]
            cff.topDictIndex[0].FullName = f"Zhujinju Song {style}"
            cff.topDictIndex[0].FamilyName = "Zhujinju Song"
            font.flavor = "woff2"
            temporary = root / "public/fonts/.reading-page.woff2"
            font.save(temporary)
            digest = hashlib.sha256(temporary.read_bytes()).hexdigest()[:12]
            filename = f"reading-page-{digest}.woff2"
            target = temporary.with_name(filename)
            temporary.replace(target)
            assert set(TTFont(target).getBestCmap()) == glyphs
            page_manifest[route] = filename
            print(route, len(glyphs), target.stat().st_size, flush=True)

(root / "app/(site)/reading-fonts.css").write_text("\n".join(output) + "\n")
(root / "lib/data/reading-fonts.json").write_text(json.dumps(manifest, indent=2) + "\n")
(root / "lib/data/page-reading-fonts.json").write_text(json.dumps(page_manifest, indent=2) + "\n")
