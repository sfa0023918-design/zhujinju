"""Isolate shared UI glyphs that otherwise fetch an entire prose fallback group.

Run with fonttools[woff] installed. Subset the existing licensed WOFF2 files;
no external typeface or outline changes. Import the generated CSS last so these
small faces take precedence for these characters only. Other CMS text retains
the complete existing fallback coverage.
"""
import hashlib
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parent.parent
manifest = json.loads((root / "lib/data/reading-fonts.json").read_text())
css = ["/* Generated by scripts/build-reading-ui-fonts.py; identical existing UI glyphs. */"]
for weight, label, characters in [(w, label, chars) for w in (400, 500) for label, chars in [("text-00", "描类述"), ("core", "首页藏品展览文章关于联系")]]:
    glyphs = set(map(ord, characters))
    source = next(group for group in manifest["groups"] if group["weight"] == weight and group["name"] == label)
    font = TTFont(root / "public/fonts" / source["file"], recalcTimestamp=False)
    assert glyphs <= set(font.getBestCmap())
    options = subset.Options()
    options.flavor = "woff2"
    options.recalc_timestamp = False
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=glyphs)
    sub.subset(font)
    font.flavor = "woff2"
    temporary = root / f"public/fonts/.reading-ui-{weight}.woff2"
    font.save(temporary)
    digest = hashlib.sha256(temporary.read_bytes()).hexdigest()[:12]
    name = f"reading-ui-{weight}-{digest}.woff2"
    target = temporary.with_name(name)
    temporary.replace(target)
    assert set(TTFont(target).getBestCmap()) == glyphs
    css.append(f'''@font-face {{
  font-family: "Zhujinju Song";
  font-style: normal;
  font-weight: {weight};
  font-display: swap;
  src: url("/fonts/{name}") format("woff2");
  unicode-range: {",".join(f"U+{cp:X}" for cp in sorted(glyphs))};
}}''')
    print(name, target.stat().st_size)
(root / "app/(site)/reading-ui-fonts.css").write_text("\n".join(css) + "\n")
