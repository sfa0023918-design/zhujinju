import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const source = readFileSync(new URL("app/(site)/reading-fonts.css", root), "utf8");
const faces = source.match(/@font-face\s*\{[^}]+\}/g) ?? [];
if (!faces.length) throw new Error("Reading font definitions are missing");
const critical = [];
const deferred = [];
for (const face of faces) {
  // Keep the original core and Latin faces available before the first render.
  // Page-specific subsets already cover reading content. The complete original
  // family remains available for new CMS characters, after the initial load.
  (/reading-song-\d+-core-|font-family: "(?:Instrument Sans|Anton|Source Serif 4|Instrument Serif)"/.test(face)
    ? critical : deferred).push(face);
}
const css = deferred.join("\n");
const hash = createHash("sha256").update(css).digest("hex").slice(0, 12);
const file = `reading-fallback-${hash}.css`;
writeFileSync(new URL("app/(site)/reading-critical-fonts.css", root), `/* Generated by scripts/prepare-reading-fonts.mjs. */\n${critical.join("\n")}\n`);
writeFileSync(new URL(`public/fonts/${file}`, root), css);
writeFileSync(new URL("lib/data/reading-fallback-stylesheet.json", root), `${JSON.stringify({ href: `/fonts/${file}` }, null, 2)}\n`);
console.log(`Reading font styles: ${critical.length} critical, ${deferred.length} deferred (${fileURLToPath(root)})`);
